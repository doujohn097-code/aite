#!/usr/bin/env node
/**
 * استبدال @protobufjs/codegen بنسخة بلا eval — ضروري لـ Cloudflare Workers.
 *
 * workerd يمنع eval()/new Function() نهائياً، بينما protobufjs (عبر سلسلة
 * firebase-admin ← @google-cloud/firestore ← google-gax) يولّد الدوال
 * ديناميكياً عند إنشاء العميل حتى في وضع preferRest.
 *
 * النسخة البديلة تتعرف على الأنماط الفعلية المستخدمة عند بناء العميل:
 * 1. منشئ الرسائل (type.js): نسخ خصائص الكائن المُمرر — بديل يدوي مكافئ.
 * 2. غلاف rpcCall (service.js): تفويض ثابت للوسائط.
 * 3. "return {}" (converter.js للرسائل الفارغة).
 * مسارات gRPC فقط (encode/decode/verify/fromObject/toObject) لا تُستدعى
 * في وضع REST، وإن استُدعيت ترفع خطأً واضحاً بدل نتيجة خاطئة صامتة.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'node_modules', '@protobufjs', 'codegen', 'index.js');

if (!existsSync(target)) process.exit(0);

const replacement = `"use strict";
/**
 * EVAL-FREE FORK of @protobufjs/codegen for Cloudflare Workers (workerd
 * forbids eval/new Function). Hand-written equivalents replace the two
 * codegen patterns used while constructing clients in Firestore REST mode.
 * Generated by scripts/patch-protobufjs.mjs — do not edit manually.
 */
module.exports = codegen;

function codegen(functionParams, functionName) {
    if (typeof functionParams === "string") {
        functionName = functionParams;
        functionParams = undefined;
    }

    var body = [];

    function Codegen(formatStringOrScope) {
        // finish the function
        if (typeof formatStringOrScope !== "string") {
            var source = body.join("\\n");
            if (formatStringOrScope && typeof formatStringOrScope === "object") {
                var scopeKeys = Object.keys(formatStringOrScope);
                var scopeValues = scopeKeys.map(function (k) { return formatStringOrScope[k]; });
                return finishScoped(source, scopeKeys, scopeValues);
            }
            return finishScopeless(source);
        }

        // otherwise append to body (formatting identical to upstream)
        var formatParams = new Array(arguments.length - 1),
            formatOffset = 0;
        while (formatOffset < formatParams.length)
            formatParams[formatOffset] = arguments[++formatOffset];
        formatOffset = 0;
        formatStringOrScope = formatStringOrScope.replace(/%([%dfijs])/g, function replace($0, $1) {
            var value = formatParams[formatOffset++];
            switch ($1) {
                case "d": case "f": return String(Number(value));
                case "i": return String(Math.floor(value));
                case "j": return JSON.stringify(value);
                case "s": return String(value);
            }
            return "%";
        });
        if (formatOffset !== formatParams.length)
            throw Error("parameter count mismatch");
        body.push(formatStringOrScope);
        return Codegen;
    }

    function toString(functionNameOverride) {
        return "function " + ((functionNameOverride || functionName) || "") + "(" +
            ((functionParams && functionParams.join(",")) || "") + "){\\n  " + body.join("\\n  ") + "\\n}";
    }

    Codegen.toString = toString;
    return Codegen;
}

codegen.verbose = false;

function finishScopeless(source) {
    if (source.indexOf("return {}") >= 0)
        return function () { return {}; };
    // protobufjs message constructor: copy provided props onto this
    if (source.indexOf("this[ks[i]]=p[ks[i]]") >= 0 || source.indexOf("if(p)for(") >= 0)
        return function GenericMessage(p) {
            if (p)
                for (var ks = Object.keys(p), i = 0; i < ks.length; ++i)
                    if (p[ks[i]] != null) this[ks[i]] = p[ks[i]];
        };
    throw new Error("protobufjs(no-eval): unsupported generated code: " + String(source).slice(0, 160));
}

function finishScoped(source, scopeKeys, scopeValues) {
    // converter.toObject for field-less messages: ("return {}")(<scope>)
    if (source.indexOf("return {}") >= 0)
        return function () { return {}; };
    // rpc service method wrapper: ("return this.rpcCall(m,q,s,r,c)")({m,q,s})
    if (source.indexOf("this.rpcCall") >= 0 && scopeKeys.length === 3) {
        var m = scopeValues[0], q = scopeValues[1], s = scopeValues[2];
        return function (r, c) {
            return this.rpcCall(m, q, s, r, c);
        };
    }
    throw new Error("protobufjs(no-eval): unsupported scoped code: " + String(source).slice(0, 160));
}
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, replacement);
console.log('[patch-protobufjs] installed eval-free codegen into @protobufjs/codegen');
